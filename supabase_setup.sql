-- Atomic admin credit. The service-role key must stay in Vercel environment variables only.
create or replace function public.admin_credit_balance(p_telegram_id text, p_amount numeric, p_reference text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_user public.store_users%rowtype;
begin
  if p_amount is null or p_amount <= 0 then raise exception 'Amount must be positive'; end if;
  select * into v_user from public.store_users where telegram_id = p_telegram_id for update;
  if not found then raise exception 'User not found'; end if;
  update public.store_users set balance = coalesce(balance,0) + p_amount where telegram_id = p_telegram_id;
  return jsonb_build_object('ok',true,'telegram_id',p_telegram_id,'credited',p_amount,'reference',p_reference);
end; $$;

-- Atomic top-up approval: a pending request can only be credited once.
create or replace function public.approve_topup_once(p_topup_id bigint, p_admin_telegram_id text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_topup public.store_topups%rowtype;
begin
  select * into v_topup from public.store_topups where id = p_topup_id for update;
  if not found then raise exception 'Top-up not found'; end if;
  if v_topup.status <> 'pending' then raise exception 'Top-up already reviewed'; end if;
  update public.store_users set balance = coalesce(balance,0) + v_topup.amount where telegram_id = v_topup.telegram_id;
  if not found then raise exception 'User not found'; end if;
  update public.store_topups set status='approved', reviewed_by=p_admin_telegram_id, reviewed_at=now() where id=p_topup_id;
  return jsonb_build_object('ok',true,'topup_id',p_topup_id,'telegram_id',v_topup.telegram_id,'amount',v_topup.amount);
end; $$;

-- Atomic checkout: lock the user and selected stock rows, debit balance, mark keys sold,
-- and write the purchase record in one transaction. Returns delivered keys only on success.
create or replace function public.purchase_and_deliver(p_telegram_id text, p_product_id bigint, p_quantity integer)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_user public.store_users%rowtype;
  v_product public.store_products%rowtype;
  v_stock_ids bigint[];
  v_keys text[];
  v_total numeric(12,2);
  v_unit_price numeric(12,2);
  v_purchase_id bigint;
begin
  if p_quantity is null or p_quantity < 1 or p_quantity > 20 then raise exception 'Invalid quantity'; end if;
  select * into v_user from public.store_users where telegram_id=p_telegram_id for update;
  if not found then raise exception 'User not found'; end if;
  select * into v_product from public.store_products where id=p_product_id and active=true for share;
  if not found then raise exception 'Product unavailable'; end if;
  v_unit_price := v_product.price;
  if v_user.role = 'reseller' then
    select price into v_unit_price from public.store_reseller_prices
    where telegram_id=p_telegram_id and product_id=p_product_id;
    if v_unit_price is null then v_unit_price := v_product.price; end if;
  end if;
  v_total := round(v_unit_price * p_quantity, 2);
  if coalesce(v_user.balance,0) < v_total then raise exception 'Insufficient balance'; end if;
  select array_agg(id), array_agg(license_key) into v_stock_ids, v_keys
  from (
    select id, license_key from public.store_stock
    where product_id=p_product_id and sold_to is null
    order by id for update skip locked limit p_quantity
  ) s;
  if coalesce(array_length(v_stock_ids,1),0) <> p_quantity then raise exception 'Insufficient stock'; end if;
  update public.store_users set balance=coalesce(balance,0)-v_total where telegram_id=p_telegram_id;
  update public.store_stock set sold_to=p_telegram_id where id=any(v_stock_ids) and sold_to is null;
  insert into public.store_purchases(telegram_id,product_id,quantity,total_price,status,created_at)
  values(p_telegram_id,p_product_id,p_quantity,v_total,'completed',now()) returning id into v_purchase_id;
  return jsonb_build_object('ok',true,'purchase_id',v_purchase_id,'total',v_total,'quantity',p_quantity,'keys',to_jsonb(v_keys));
end; $$;

